// ---------------------------------------------------------------------------
//  离屏绘制的自检工具
// ---------------------------------------------------------------------------
//  用公开 API 采样一张离屏 IMAGE，把每条绘制路径的真实结果与 alpha 情况打出来。
//  存在的理由：EGE 里"直接写像素缓冲"（cleardevice / putimage_alpha*）与
//  "走 GDI"（bar / roundrect / outtextxy）两条路径对 alpha 的处理完全不同，
//  出问题时现象是"画了但看不见 / 存成 PNG 全黑"，很难靠肉眼定位。
//  详见 ui/gfx_util.h 的说明。
//
//  返回 0 表示全部符合预期。
// ---------------------------------------------------------------------------
int gfxSelfTest();

// 把图集渲染成一张带标注的对照图（默认 build/atlas_dump.png）
int atlasDump();

// --------------------------------------------------------------------------
//  翻转棋求解器自检
// --------------------------------------------------------------------------
//  GF(2) 线性代数 + 零空间枚举是这个游戏的 AI 与高级提示的全部依据，
//  所以要用暴力枚举把它盯死：
//    * 3x3：对全部 512 个局面，比对“求解器给的步数”与“暴力枚举的最少步数”
//    * 4x4：随机抽样，同样与暴力枚举比对（2^16 = 65536 枚举量）
//    * 5x5：随机抽样，验证“按求解器的方案确实能全部同色”
//    * 零空间：随机采样解空间，验证 required 标记确实是“所有解都按”
//  返回 0 表示全部通过。
// --------------------------------------------------------------------------
int flipSolverTest();

// --------------------------------------------------------------------------
//  窗口 / 坐标自检
// --------------------------------------------------------------------------
//  用来定位"鼠标点击位置与画面响应位置不一致"这类问题。
//
//  背景：EGE 按 dc_w x dc_h 请求画布，窗口客户区由 init_instance() 用
//      dw = SM_CXFRAME * 2
//      dh = SM_CYFRAME + SM_CYCAPTION * 2
//  估算后建窗，再由 graphupdate() 把客户区校正到 dc_w x dc_h。
//  而鼠标消息里的坐标是**客户区坐标**（直接取自 lParam，没有 DPI 变换），
//  所以一旦客户区最终不等于 1280x800，点击就会相对画面出现偏移。
//
//  本自检在真实渲染若干帧之后（此时校正逻辑已经跑过）打印：
//      * EGE 认为的画布尺寸 getwidth()/getheight()
//      * 窗口真实的客户区与窗口矩形（用 EGE 的窗口类名找回 HWND）
//      * 两者是否一致；不一致给出按比例换算后的"真实偏移"
//      * 系统 DPI 与各项窗口度量
//  返回 0 表示一致。
// --------------------------------------------------------------------------
int windowInfoCheck();

// --------------------------------------------------------------------------
//  绘制 <-> 命中 一致性自检
// --------------------------------------------------------------------------
//  验证"棋盘画在哪个像素位置"与"hitTest 认为格子在哪"严格一致。
//  两者只要差一点，手感就是"点不准"，而且很难用肉眼看出来。
//  做法：把棋盘底+网格渲染到离屏图按颜色扫描出包围盒，
//  再逐格检查格子中心（及中心周边若干点）hitTest 回来是否还是同一格。
//  覆盖落格（5x5 / 8x8 / 15x15）与交叉点（9x9 / 9x10 / 19x19）两类棋盘。
//  返回 0 表示全部一致。
// --------------------------------------------------------------------------
int hitTestCheck();

// --------------------------------------------------------------------------
//  五子棋自检
// --------------------------------------------------------------------------
//  覆盖三块：
//    * 胜负判定：4 个方向各自成五、长连、未成五不算胜
//    * 禁手判定：长连/双四/双活三为禁手；成五优先于禁手（成五不算禁手）
//    * AI 关键行为：能抓成五、必须挡对方的成五、AI 对 AI 能终局
//  这些都是"错了就整盘棋不成立"的性质，比手感更值得自动化验证。
//  返回 0 表示全部通过。
// --------------------------------------------------------------------------
int gomokuTest();

// --------------------------------------------------------------------------
//  象棋 perft 自检
// --------------------------------------------------------------------------
//  perft = 从初始局面出发，逐层统计合法着法总数。
//  这是验证走子规则**最客观**的手段：数值对不上，说明马腿/象眼/炮隔子/
//  兵卒/九宫/飞将/将军限制里至少有一处错了，而且能通过逐层数值定位。
//
//  参考值（中国象棋标准初始局面）：
//      depth 1 = 44
//      depth 2 = 1920
//      depth 3 = 79666
//      depth 4 = 3290240      （较慢，默认不测）
//  返回 0 表示全部吻合。
// --------------------------------------------------------------------------
int xiangqiPerft();

// --------------------------------------------------------------------------
//  棋子 -> 图集精灵 的映射核对
// --------------------------------------------------------------------------
//  res/chesses.txt 里的名字（shuai1 / shi1 / ...）**没有标明哪个是红哪个是黑**，
//  而且缺少红方的「炮」。所以我按字形做了假设，但这需要人工确认一次。
//
//  本命令把整张映射表以 ASCII 打到控制台：
//      piece            sprite        inAtlas
//      red   King       shuai1        yes
//      red   Cannon     (none)        no      <- 文字兜底
//      ...
//  然后再把初始局面按"每格用哪个精灵"画成一张字符棋盘，
//  直接对照`chess --atlas-dump`生成的对照图即可判断假设是否成立。
//
//  控制台只输出 ASCII：源码是按 GBK 生成窄字符串的，终端是 UTF-8，
//  打中文会乱码，反而看不出问题。
// --------------------------------------------------------------------------
int dumpBoard();

// --------------------------------------------------------------------------
//  围棋自检
// --------------------------------------------------------------------------
//  围棋最容易出错的是"提子"与"禁着"这几条规则，而且错了以后表现得非常隐蔽
//  （局面看起来还挺正常，只是某个子莫名其妙不见了）。这里逐条验证：
//    * 提子：白子被围成 1 气后提掉；整块被提时每一枚都要消失
//    * 禁自杀：填自己的最后一个气是非法着（除非同时提到对方）
//    * 简单劫：立刻提回是非法着；隔一手后可以提回
//    * 停手终局：双方连续停手后进入终局并给出数子结果
//    * 悔棋：整块被提后悔棋，**每一枚**被提的子都要回到原位
//    * 数子：单色围空的区域归该色，双方共气的空区不计
//  返回 0 表示全部通过。
// --------------------------------------------------------------------------
int goRulesTest();

// --------------------------------------------------------------------------
//  AI 时间预算回归测试
// --------------------------------------------------------------------------
//  专门盯住一类很容易写错、而且**症状极隐蔽**的 bug：
//  如果搜索里的计时器是"函数局部 static"（只初始化一次、永不重置），
//  而时间预算是**相对**值时，那么第一次搜索之后的所有搜索都会立刻判定超时。
//  此时 AI 照样能返回合法的着法，测试"能走棋"也会通过，
//  但引擎实际上完全没用时间预算 —— 等级设置形同失效。
//
//  所以这里连续跑多次搜索，断言**后面几次**的搜索量与第一次同一量级。
//  返回 0 表示通过。
// --------------------------------------------------------------------------
int aiBudgetTest();

// --------------------------------------------------------------------------
//  象棋棋子叠层渲染自检
// --------------------------------------------------------------------------
//  象棋棋子是"底盘 + 字面"两层：
//    chineseChess  木色实心圆盘（实测填充率 64%）  -> 底盘
//    shuai1 等 13 个  只有笔画（填充率 4~8%）      -> 字面，透明底
//  只画字面会得到一排"悬空的字"（曾经就是这样）。
//
//  本自检离屏渲染象棋棋盘，然后对每个有子的交叉点在半径 0.30*cell 的圆周上
//  采样 16 点：
//    * 有子的点：该圈应几乎被底盘覆盖（非棋盘底色/非棋盘线）—— 验证底盘存在
//    * 空交叉点：几乎不该有非棋盘像素                     —— 验证没有多余绘制
//  返回 0 表示通过。
// --------------------------------------------------------------------------
int xiangqiPieceRenderTest();

// --------------------------------------------------------------------------
//  中文编码链路自检
// --------------------------------------------------------------------------
//  这个测试针对一类**极隐蔽**的构建配置错误：编译器没有把源码里的中文
//  转换成预期的执行字符集（例如 xmake 的 {tools=...} 过滤器写错，flag 被
//  静默丢弃）。此时编译照常成功、没有任何警告，但界面中文**全部乱码**。
//
//  三部分检查：
//    1) 打印字面量的**原始字节** —— 直接看出执行字符集到底是 GBK 还是 UTF-8
//    2) 打印系统 ACP 与 EGE 当前 codepage，并做一次
//       MultiByteToWideChar(codepage, 字面量) 往返，验证能否解出正确汉字
//    3) **端到端像素比对**（最关键）：把同一个字符串分别用
//         窄字符 API  outtextxy(x, y, "中文")
//         宽字符 API  outtextxy(x, y, L"中文")
//       渲染到离屏图，逐像素比对。宽字符路径不经过代码页转换，是"已知正确"
//       的参照。两条路径渲染结果一致 <=> 编码链路正确。
//       同时断言两张图都有足够的墨迹，避免"字体画不出字 -> 两图都是空白 -> 假通过"。
//  返回 0 表示通过。
// --------------------------------------------------------------------------
int encodingTest();

// --------------------------------------------------------------------------
//  字号 / 排版自检
// --------------------------------------------------------------------------
//  字号调大之后，"文字有没有溢出容器"不能靠看截图判断：
//  截图会被缩放、压缩，差几个像素根本看不出来，而 CJK 的实际宽度
//  随字体差异很大，凭字数估算也会错。
//
//  所以这里直接用文字的度量 API 算出换行后的高度，与布局常量比对：
//    * 菜单卡片 / 右侧面板的简介文字是否塞得进预留高度
//    * 卡片网格总高度是否溢出内容区
//    * 面板里最后一组 chip 的底部是否压到贴底的"重置/开始"按钮
//      （这一条走 MenuScene::optionsContentBottom，和真实布局同一份代码）
//
//  常量取自 menu_layout 与 theme，所以调字号后自检会自动跟着变。
//  返回 0 表示通过。
// --------------------------------------------------------------------------
int uiLayoutCheck();

